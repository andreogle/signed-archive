// Regenerates the `airnodes` and `feeds` lists in signed-archive.yaml from @api3/api-integrations, API3's own list
// of data providers and the feeds each one serves. Everything above the marker line (the settings) is kept as is.
// Run `bun run airnodes` after bumping that package. With `--check` it changes nothing and fails if the file is out of
// date, so a Dependabot bump that adds a provider or feed shows up in CI. Usage: bun scripts/airnodes.ts [path]
import { apisData, deriveTemplateId, getAllDataFeeds, getSupportedProvidersForDataFeed } from '@api3/api-integrations';

const MARKER =
  '# ---- Generated by `bun run airnodes` from @api3/api-integrations. Everything below this line is replaced. ----';
const check = process.argv.includes('--check');
const path = process.argv.slice(2).find((arg) => !arg.startsWith('--')) ?? 'signed-archive.yaml';

// Mock providers have no Signed API URL and never serve real data.
const apis = Object.values(apisData)
  .filter((api) => api.signedApiUrl !== '')
  .sort((a, b) => a.alias.localeCompare(b.alias));

// JSON strings are valid YAML, and quoting keeps YAML from reading 0x... as a number.
const q = JSON.stringify;
const lines = [MARKER, '', "# Providers to archive: each is polled on API3's Signed API and on its own.", 'airnodes:'];
for (const { alias, airnode, signedApiUrl } of apis) {
  lines.push(`  - alias: ${q(alias)}`, `    airnode: ${q(airnode)}`, `    signedApiUrl: ${q(signedApiUrl)}`);
}
lines.push('', '# Feed name -> provider alias -> base template ID. OEV template IDs are keccak256 of these.', 'feeds:');
const byAlias = new Map(apis.map((api) => [api.alias, api.airnode]));
for (const feedName of getAllDataFeeds().sort()) {
  const providers = getSupportedProvidersForDataFeed(feedName)
    .sort()
    .flatMap((alias) => {
      const airnodeAddress = byAlias.get(alias);
      return airnodeAddress ? [`    ${q(alias)}: ${q(deriveTemplateId({ feedName, airnodeAddress }))}`] : [];
    });
  lines.push(providers.length > 0 ? `  ${q(feedName)}:` : `  ${q(feedName)}: {}`, ...providers);
}

const current = await Bun.file(path).text();
const markerAt = current.indexOf(MARKER);
const settings = (markerAt === -1 ? current : current.slice(0, markerAt)).trimEnd();
const next = `${settings}\n\n${lines.join('\n')}\n`;

if (!check) {
  await Bun.write(path, next);
} else if (current !== next) {
  console.error(`${path} is out of date. Run \`bun run airnodes\` and commit the result.`);
  process.exit(1);
}
