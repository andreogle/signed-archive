// Regenerates config/airnodes.yaml and config/feeds.yaml from @api3/api-integrations, API3's own list of data
// providers and the feeds each one serves. Run `bun run airnodes` after bumping that package. With `--check` it
// changes nothing and fails if either file is out of date, so a Dependabot bump that adds a provider or feed shows up
// in CI. The settings file names these files under `catalog`; these are the defaults.
import { apisData, deriveTemplateId, getAllDataFeeds, getSupportedProvidersForDataFeed } from '@api3/api-integrations';

const check = process.argv.includes('--check');
const HEADER = '# Generated by `bun run airnodes` from @api3/api-integrations. Edit the source, not this file.';

// Mock providers have no Signed API URL and never serve real data.
const apis = Object.values(apisData)
  .filter((api) => api.signedApiUrl !== '')
  .sort((a, b) => a.alias.localeCompare(b.alias));

// JSON strings are valid YAML, and quoting keeps YAML from reading 0x... as a number.
const q = JSON.stringify;
const airnodes = [HEADER, "# Providers to archive: each is polled on API3's Signed API and on its own.", 'airnodes:'];
for (const { alias, airnode, signedApiUrl } of apis) {
  airnodes.push(`  - alias: ${q(alias)}`, `    airnode: ${q(airnode)}`, `    signedApiUrl: ${q(signedApiUrl)}`);
}

const feeds = [
  HEADER,
  '# Feed name -> provider alias -> base template ID. OEV template IDs are keccak256 of these.',
  'feeds:',
];
const byAlias = new Map(apis.map((api) => [api.alias, api.airnode]));
for (const feedName of getAllDataFeeds().sort()) {
  const providers = getSupportedProvidersForDataFeed(feedName)
    .sort()
    .flatMap((alias) => {
      const airnodeAddress = byAlias.get(alias);
      return airnodeAddress ? [`    ${q(alias)}: ${q(deriveTemplateId({ feedName, airnodeAddress }))}`] : [];
    });
  feeds.push(providers.length > 0 ? `  ${q(feedName)}:` : `  ${q(feedName)}: {}`, ...providers);
}

for (const [path, lines] of [
  ['config/airnodes.yaml', airnodes],
  ['config/feeds.yaml', feeds],
] as const) {
  const next = `${lines.join('\n')}\n`;
  const file = Bun.file(path);
  if (!check) await Bun.write(path, next);
  else if (!(await file.exists()) || (await file.text()) !== next) {
    console.error(`${path} is out of date. Run \`bun run airnodes\` and commit the result.`);
    process.exit(1);
  }
}
