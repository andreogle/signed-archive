import type { Address } from 'viem';
import airnodes from './airnodes.json' with { type: 'json' };

export const BASE_URL = 'https://signed-api.api3.org';

// `public` serves base-feed data delayed by ~15 s; `public-oev` serves fresher data signed for the OEV domain.
export const ENDPOINTS = ['public', 'public-oev'] as const;
export type Endpoint = (typeof ENDPOINTS)[number];
export const isEndpoint = (value: unknown): value is Endpoint => (ENDPOINTS as readonly unknown[]).includes(value);

// Every provider pushes the same signed data to API3's Signed API and to its own. Archiving both gives a second
// source when one is down, and shows whether API3's copy ever lacks data the provider published.
export const SOURCES = ['api3', 'provider'] as const;
export type Source = (typeof SOURCES)[number];
export const isSource = (value: unknown): value is Source => (SOURCES as readonly unknown[]).includes(value);

// Generated by `bun run airnodes` from API3's provider list. The Signed API's own `/airnodes`
// route is disabled, so this is the only list available.
export const AIRNODES: readonly { alias: string; airnode: Address; signedApiUrl: string }[] = airnodes.map(
  ({ alias, airnode, signedApiUrl }) => ({ alias, airnode: airnode as Address, signedApiUrl })
);

// Feeds are re-signed every few seconds whether or not the price moved, so polling faster buys
// more rows, not better data. The floor keeps a typo from hammering the API.
export const MIN_INTERVAL_SECONDS = 15;
export const DEFAULT_INTERVAL_SECONDS = 60;
export const DEFAULT_DB_PATH = 'data/archive.sqlite';
// The explorer listens on loopback unless told otherwise, so it isn't exposed to the network by accident.
export const DEFAULT_HOST = '127.0.0.1';
export const DEFAULT_PORT = 3000;

export const REQUEST_TIMEOUT_MS = 10_000;
export const MAX_BACKOFF_MS = 30 * 60 * 1000;
export const USER_AGENT = 'signed-archive/0.1 (polite poller, one request at a time)';
